<?php

declare(strict_types=1);

namespace CtPassStore\Tests\Load\Helpers;

use CtPassStore\Infrastructure\Store\RecordSigner;
use CtPassStore\Infrastructure\Store\SignedFileCache;
use CtPassStore\Infrastructure\Time\SystemClock;
use CtPassStore\Tests\Contract\Helpers\BackendSandboxManager;
use CtPassStore\Tests\Support\PhpProcess;
use Psr\Log\NullLogger;

/**
 * A deploy-like copy of the backend in a temporary folder, for the load test: `public/index.php` and
 * `bin/cleanup.php` are copied (a symlinked folder would make `__DIR__` point back to the real `config/`), `vendor/`
 * is a symlink, and `config/`, `cache/` and `logs/` are its own. The generated `credentials.php` never touches the
 * developer's real one.
 */
final class LoadSandbox
{
    private const BACKEND = __DIR__ . '/../../..';

    public readonly string $folder;

    private ?BackendSandboxManager $server = null;

    private string $baseUrl = '';

    /**
     * @param array<string, mixed> $credentials the complete content of the sandbox's credentials.php
     */
    public function __construct(#[\SensitiveParameter] array $credentials, #[\SensitiveParameter] private readonly string $jwtSecret)
    {
        $this->folder = sys_get_temp_dir() . '/ctps-load-' . bin2hex(random_bytes(6));
        foreach (['public', 'bin', 'logs'] as $dir) {
            mkdir($this->folder . '/' . $dir, 0o700, true);
        }
        mkdir($this->folder . '/config', 0o700);
        mkdir($this->folder . '/cache', 0o700);
        copy(self::BACKEND . '/public/index.php', $this->folder . '/public/index.php');
        copy(self::BACKEND . '/bin/cleanup.php', $this->folder . '/bin/cleanup.php');
        copy(self::BACKEND . '/VERSION', $this->folder . '/VERSION');
        symlink((string) realpath(self::BACKEND . '/vendor'), $this->folder . '/vendor');

        $file = $this->folder . '/config/credentials.php';
        touch($file);
        chmod($file, 0o600);
        file_put_contents($file, "<?php\n\n// Generated by the load test; removed with the sandbox.\nreturn json_decode(base64_decode('"
            . base64_encode(json_encode($credentials, JSON_THROW_ON_ERROR))
            . "'), true, 512, JSON_THROW_ON_ERROR);\n");
    }

    public function start(): void
    {
        $socket = stream_socket_server('tcp://127.0.0.1:0');
        if ($socket === false) {
            throw new \RuntimeException('No free port.');
        }
        $port = (int) substr((string) strrchr((string) stream_socket_get_name($socket, false), ':'), 1);
        fclose($socket);
        $this->server = new BackendSandboxManager('127.0.0.1', $port, $this->folder . '/public', 1);
        $this->server->start();
        $this->baseUrl = $this->server->getBaseUrl();
    }

    public function baseUrl(): string
    {
        return $this->baseUrl;
    }

    /**
     * Puts the given raw settings object into this sandbox's settings cache, as the backend would cache it after
     * loading it from ChurchTools (valid for the settings TTL of 300 s). Only this sandbox's cache changes.
     *
     * @param array<string, mixed> $rawSettings
     */
    public function plantSettings(array $rawSettings): void
    {
        $this->cache()->put('settings', $rawSettings, 300);
    }

    /** Forgets which persons were confirmed active, so the next read asks ChurchTools again. */
    public function clearPersonsCache(): void
    {
        $this->cache()->forget('persons-active');
    }

    /**
     * Removes the web cron's cooldown record (spec 4.12) from this sandbox's security store.
     *
     * @return bool whether the record existed
     */
    public function clearCleanupCooldown(): bool
    {
        $path = $this->folder . '/cache/sec-' . hash('sha256', 'cooldown:cleanup:web-cron') . '.json';
        if (!is_file($path)) {
            return false;
        }
        unlink($path);

        return true;
    }

    /**
     * @param list<string> $arguments
     * @return array{exit: int, output: string, ms: float}
     */
    public function runCleanupScript(array $arguments): array
    {
        $start = hrtime(true);
        $result = PhpProcess::run([$this->folder . '/bin/cleanup.php', ...$arguments], ['PATH' => (string) getenv('PATH')], $this->folder);

        return $result + ['ms' => (hrtime(true) - $start) / 1e6];
    }

    public function stopAndRemove(): void
    {
        $this->server?->stop();
        $this->server = null;
        if (is_dir($this->folder)) {
            self::remove($this->folder);
        }
    }

    private function cache(): SignedFileCache
    {
        return new SignedFileCache($this->folder . '/cache', new RecordSigner($this->jwtSecret, SignedFileCache::PURPOSE), new SystemClock(), new NullLogger());
    }

    private static function remove(string $path): void
    {
        if (is_link($path) || is_file($path)) {
            unlink($path);

            return;
        }
        foreach (scandir($path) ?: [] as $name) {
            if ($name !== '.' && $name !== '..') {
                self::remove($path . '/' . $name);
            }
        }
        rmdir($path);
    }
}
